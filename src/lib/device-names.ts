/**
 * Sanitize a client-supplied device label before storing it.
 * Strips control characters and caps the length.
 */
export function sanitizeDevice(value: unknown): string {
  if (typeof value !== 'string') return '';
  return value
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .trim()
    .slice(0, 60);
}

// Labels too generic to identify a physical device (UA-parse fallbacks).
const GENERIC_DEVICES = new Set([
  '',
  'Unknown',
  'Windows',
  'Linux',
  'Mac',
  'Android',
  'iPhone',
  'iPad',
  'iPod',
]);

/**
 * Whether a device label is specific enough to use as a merge key when the
 * same physical machine shows up again with a new visitor id (cleared
 * storage, second browser, PWA vs tab, ...). Generic labels like "Windows"
 * would falsely merge unrelated devices behind the same NAT.
 */
export function isMergeableDevice(device: string): boolean {
  return !!device && !GENERIC_DEVICES.has(device);
}

/**
 * Resolve a raw device model code (e.g. "RMX3085", "SM-S928B") to a
 * marketing-friendly name. Falls back to the raw code when unknown.
 */
export function resolveModel(code: string): string {
  if (!code) return '';
  const trimmed = code.trim();
  if (!trimmed) return '';

  const direct = MODEL_MAP[trimmed];
  if (direct) return direct;

  const upper = trimmed.toUpperCase();

  // Case-insensitive + region-suffix tolerant lookup (SM-S928B_XX, SM-S928B-EUX)
  const base = upper.replace(/[_-][A-Z]{2,4}$/, '');
  for (const key of Object.keys(MODEL_MAP)) {
    const k = key.toUpperCase();
    if (k === upper || (base !== upper && k === base)) return MODEL_MAP[key];
  }

  return trimmed;
}

/**
 * Infer an iPhone/iPad model name from physical screen pixels.
 * Returns '' when not an Apple device or the resolution is unknown.
 */
export function resolveAppleModel(
  physicalWidth: number,
  physicalHeight: number,
  isPad: boolean
): string {
  if (!physicalWidth || !physicalHeight) return '';

  // Normalize to portrait (width < height)
  const w = Math.min(physicalWidth, physicalHeight);
  const h = Math.max(physicalWidth, physicalHeight);
  const table = isPad ? IPAD_MAP : IPHONE_MAP;
  return table[`${w}x${h}`] || '';
}
